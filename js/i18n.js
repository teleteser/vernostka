const DEFAULT_CATEGORIES = ['category_food', 'category_drugstore', 'category_restaurant', 'category_clothing', 'category_other'];

function detectDefaultLang() {
  const nav = (navigator.language || 'en').toLowerCase();
  return nav.startsWith('sk') ? 'sk' : 'en';
}

const i18n = {
  lang: detectDefaultLang(),
  t(key, vars) {
    let str = (I18N[this.lang] && I18N[this.lang][key]) || I18N.en[key] || key;
    if (vars) {
      Object.keys(vars).forEach((k) => { str = str.replace(`{${k}}`, vars[k]); });
    }
    return str;
  },
  setLang(lang) {
    this.lang = lang;
  }
};
